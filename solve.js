// A faster drop-in for makefun-site 1.0.0: run(input) returns exactly the answer
// makefun-site's build returns for the same input, as a JSON object of path -> text.
// Written from the makefun-site README's rules (the code is the reference where
// the two differ). Same pipeline, faster machinery:
//
// - front matter: indexOf line scan, no split/join round trip;
// - Markdown: a streaming block renderer (no token objects), lines classified by
//   first characters, inline parsed over index ranges into a chunk array (no
//   substring slicing, no per-character escape calls);
// - slugify: cached per distinct string (NFKD normalisation is the slow part);
// - templates: parsed once per build, rendered into a chunk array;
// - per-source work (words, card) computed once and reused.

